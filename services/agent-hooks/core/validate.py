# A sha must carry both a digit and a letter, or hex-alphabet English
# ("defaced", "effaced") is refused. The lookbehind keeps a '#abc123' CSS
# colour from reading as a commit.
_PROJECT_SHA = re.compile(
    r"(?<![#\w])(?=[0-9a-f]{7,40}\b)(?=[0-9a-f]*[0-9])(?=[0-9a-f]*[a-f])[0-9a-f]{7,40}\b"
)
# A workstation path, not a URL path: the slash must not follow a word char
# or a dot, so 'https://x/home/' and 'a.b/tmp/' do not match.
_PROJECT_ABS_PATH = re.compile(r"(?<![\w.])/(?:home|Users|root|tmp|var|etc|opt|srv|mnt)/")


def _project_window_seconds(start: object, end: object) -> int:
    """Seconds from window.start to window.end; both must be RFC 3339."""
    for name, value in (("start", start), ("end", end)):
        if not _is_rfc3339_datetime(value):
            raise ContractViolation(f"project data.window.{name} must be an RFC 3339 date-time")

    def _parse(value: str) -> datetime:
        return datetime.fromisoformat(value[:-1] + "+00:00" if value.endswith("Z") else value)

    return int((_parse(end) - _parse(start)).total_seconds())


def _project_refuse_markers(field: str, text: str, markers) -> None:
    for pattern, what in markers:
        hit = pattern.search(text)
        if hit:
            raise ContractViolation(
                f"project external report.{field} contains {what} ({hit.group(0)!r}); "
                "that fact belongs on the audience=internal event"
            )


def _assert_project_artifact_representation(
    where: str, rep: object
) -> None:
    """One representation (artifact body or render twin): content ref is its own sha."""
    if not isinstance(rep, dict):
        raise ContractViolation(f"project {where} must be an object")
    sha = rep.get("sha256")
    content = rep.get("content")
    if not isinstance(content, dict):
        raise ContractViolation(f"project {where}.content must be an object")
    expected_ref = f"sha256:{sha}" if isinstance(sha, str) and sha else None
    if content.get("ref") != expected_ref:
        raise ContractViolation(
            f"project {where}.content.ref must equal 'sha256:' + {where}.sha256"
        )
    if content.get("storage") != "content-addressed":
        raise ContractViolation(
            f"project {where}.content.storage must be 'content-addressed'"
        )


def _assert_project_artifact(envelope: dict, data: dict, slug: str) -> None:
    """Cross-field invariants for bloodbank.project.artifact.created (§11.4).

    The schema fixes the shape; this fixes what it cannot see: the content
    refs are bound to the digests, the causation chain names the agent event
    the bytes were captured from, the detection basis is one of the
    deterministic adapters (or an operator resolution of a held capture), and
    no workstation path leaks into the payload.
    """
    _project_refuse_paths_anywhere(data, "data")

    artifact = data.get("artifact")
    if not isinstance(artifact, dict):
        raise ContractViolation("project data.artifact must be an object")
    _assert_project_artifact_representation("data.artifact", artifact)
    render = artifact.get("render")
    if render is not None:
        _assert_project_artifact_representation("data.artifact.render", render)
        if render.get("sha256") == artifact.get("sha256"):
            raise ContractViolation(
                "project data.artifact.render.sha256 must differ from the "
                "canonical sha256 (a render twin is a different byte sequence)"
            )

    origin = data.get("origin")
    if not isinstance(origin, dict):
        raise ContractViolation("project data.origin must be an object")
    if origin.get("basis") not in PROJECT_ARTIFACT_BASES:
        raise ContractViolation(
            "project data.origin.basis must be one of "
            f"{sorted(PROJECT_ARTIFACT_BASES)}"
        )
    source_event = origin.get("source_event")
    if not isinstance(source_event, dict):
        raise ContractViolation("project data.origin.source_event must be an object")
    # A report-derived artifact is only ever caused by the report event, and
    # a report event only ever yields that basis (or an operator resolution).
    basis = origin.get("basis")
    from_report = source_event.get("type") == PROJECT_ACTIVITY_TYPE
    if basis == "project_activity_report" and not from_report:
        raise ContractViolation(
            "project data.origin.basis 'project_activity_report' requires "
            f"source_event.type {PROJECT_ACTIVITY_TYPE!r}"
        )
    if from_report and basis not in ("project_activity_report", "operator_resolution"):
        raise ContractViolation(
            f"project source_event.type {PROJECT_ACTIVITY_TYPE!r} requires basis "
            "'project_activity_report' (or an operator_resolution)"
        )
    if envelope.get("causationid") != source_event.get("id"):
        raise ContractViolation(
            "project envelope.causationid must equal "
            "data.origin.source_event.id (the artifact fact is caused by the "
            "agent event whose bytes were captured)"
        )
    if not _is_rfc3339_datetime(origin.get("created_at")):
        raise ContractViolation(
            "project data.origin.created_at must be an RFC 3339 date-time"
        )


def _project_refuse_paths_anywhere(value: object, where: str) -> None:
    """No workstation path in any string of a project payload (§11.4 hygiene)."""
    if isinstance(value, str):
        hit = _PROJECT_ABS_PATH.search(value)
        if hit:
            raise ContractViolation(f"project {where} contains an absolute filesystem path ({hit.group(0)!r})")
    elif isinstance(value, dict):
        for key, item in value.items():
            _project_refuse_paths_anywhere(item, f"{where}.{key}")
    elif isinstance(value, list):
        for index, item in enumerate(value):
            _project_refuse_paths_anywhere(item, f"{where}[{index}]")


def assert_watch_invariants(envelope: dict) -> None:
    """Enforce cross-field invariants for the watch domain (§11.1, §11.2).

    JSON Schema fixes the shape; this fixes what it cannot see across fields:
    the ordering bucket is the target's own id, and the envelope causationid is
    the id of the event the fact answers (the matched source event for a
    detection, the detection for a routing outcome).
    """
    if envelope.get("domain") != "watch":
        return

    data = envelope.get("data")
    if not isinstance(data, dict):
        raise ContractViolation("watch event data must be an object")
    watch_id = data.get("watch_id")
    if not isinstance(watch_id, str) or not watch_id:
        raise ContractViolation("watch data.watch_id must be a non-empty string")
    if envelope.get("ordering_key") != f"watch:{watch_id}":
        raise ContractViolation(
            f"watch envelope.ordering_key must be 'watch:{watch_id}' (§11.1), "
            f"got {envelope.get('ordering_key')!r}"
        )

    parent_field = {
        "bloodbank.watch.target.detected": "source_event_id",
        "bloodbank.watch.target.routed": "detection_event_id",
    }.get(envelope.get("type"))
    if parent_field and envelope.get("causationid") != data.get(parent_field):
        raise ContractViolation(
            f"watch envelope.causationid must equal data.{parent_field}, "
            f"got {envelope.get('causationid')!r} vs {data.get(parent_field)!r}"
        )


def assert_project_invariants(envelope: dict) -> None:
    """Enforce cross-field invariants for the project domain (§11.4).

    JSON Schema fixes the shape; this fixes what the schema cannot see across
    fields: the ordering bucket is the project's slug, the correlation is the
    run, the window and token arithmetic add up, and an external report cannot
    carry the project's own ticket keys, commit shas or workstation paths.
    """
    if envelope.get("domain") != "project":
        return

    if envelope.get("type") == APP_LAUNCH_TYPE:
        assert_app_launch_invariants(envelope)
        return

    data = envelope.get("data")
    if not isinstance(data, dict):
        raise ContractViolation("project event data must be an object")
    if data.get("schema_version") != 1:
        raise ContractViolation("project data.schema_version must be 1")

    project = data.get("project")
    if not isinstance(project, dict):
        raise ContractViolation("project data.project must be an object")
    slug = project.get("slug")
    if not isinstance(slug, str) or not slug.strip():
        raise ContractViolation("project data.project.slug must be a non-empty string")
    if envelope.get("ordering_key") != f"project:{slug}":
        raise ContractViolation(
            f"project envelope.ordering_key must be 'project:{slug}' (§11.1), "
            f"got {envelope.get('ordering_key')!r}"
        )

    if envelope.get("type") == PROJECT_ARTIFACT_TYPE:
        _assert_project_artifact(envelope, data, slug)
        return

    if envelope.get("type") != PROJECT_ACTIVITY_TYPE:
        # Deployments and later project facts share the bucket rule above and the
        # domain's path hygiene; the window, token and audience rules are the report's.
        _project_refuse_paths_anywhere(data, "data")
        return

    audience = data.get("audience")
    if audience not in PROJECT_AUDIENCES:
        raise ContractViolation("project data.audience must be 'internal' or 'external'")

    generator = data.get("generator")
    if not isinstance(generator, dict):
        raise ContractViolation("project data.generator must be an object")
    if envelope.get("correlationid") != generator.get("run_id"):
        raise ContractViolation(
            "project envelope.correlationid must equal data.generator.run_id "
            "(one skill run is one correlation; both audiences share it)"
        )

    window = data.get("window")
    if not isinstance(window, dict):
        raise ContractViolation("project data.window must be an object")
    seconds = _project_window_seconds(window.get("start"), window.get("end"))
    if seconds <= 0:
        raise ContractViolation("project data.window.end must be after data.window.start")
    duration = window.get("duration_seconds")
    if not isinstance(duration, int) or isinstance(duration, bool) or duration != seconds:
        raise ContractViolation(
            f"project data.window.duration_seconds must equal end - start ({seconds}s)"
        )
    basis = window.get("basis")
    if basis not in PROJECT_WINDOW_BASES:
        raise ContractViolation(
            "project data.window.basis must be previous_report, cap_24h or explicit"
        )
    if basis == "cap_24h" and seconds != 86400:
        raise ContractViolation("project data.window.basis cap_24h requires an 86400s window")
    if basis == "previous_report" and not window.get("previous_event_id"):
        raise ContractViolation(
            "project data.window.basis previous_report requires previous_event_id"
        )

    tokens = data.get("tokens")
    if not isinstance(tokens, dict) or not isinstance(tokens.get("by_agent"), dict):
        raise ContractViolation("project data.tokens must be an object carrying by_agent")
    grand = 0
    for agent, bucket in tokens["by_agent"].items():
        if bucket is None:
            continue
        if not isinstance(bucket, dict):
            raise ContractViolation(f"project data.tokens.by_agent.{agent} must be an object or null")
        values = [bucket.get(part) for part in PROJECT_TOKEN_PARTS] + [bucket.get("total")]
        if not all(isinstance(v, int) and not isinstance(v, bool) for v in values):
            raise ContractViolation(f"project data.tokens.by_agent.{agent} values must be integers")
        if sum(values[:-1]) != bucket["total"]:
            raise ContractViolation(
                f"project data.tokens.by_agent.{agent}.total must equal "
                "input + output + cache_read + cache_write"
            )
        grand += bucket["total"]
    if tokens.get("total") != grand:
        raise ContractViolation(
            f"project data.tokens.total must equal the sum of by_agent totals ({grand})"
        )

    report = data.get("report")
    if not isinstance(report, dict):
        raise ContractViolation("project data.report must be an object")

    if audience == "external":
        present = [f for f in PROJECT_INTERNAL_ONLY_FIELDS if f in data]
        if present:
            raise ContractViolation(f"project external report must not carry {present}")
        ticket_markers = []
        identifier = project.get("identifier")
        if isinstance(identifier, str) and identifier:
            ticket_markers.append(
                (re.compile(rf"\b{re.escape(identifier)}-\d+\b"), "a ticket key")
            )
        text_markers = ticket_markers + [
            (_PROJECT_SHA, "a commit sha"),
            (_PROJECT_ABS_PATH, "an absolute filesystem path"),
        ]
        for field in ("title", "raw", "markdown"):
            value = report.get(field)
            if isinstance(value, str):
                _project_refuse_markers(field, value, text_markers)
        html = report.get("html")
        if isinstance(html, str):
            _project_refuse_markers("html", html, ticket_markers)
    else:
        missing = [f for f in PROJECT_INTERNAL_ONLY_FIELDS if f not in data]
        if missing:
            raise ContractViolation(f"project internal report must carry {missing}")


_GAME_SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
