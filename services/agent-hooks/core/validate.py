def _split_type(ce_type: str) -> tuple[str, str, str, str]:
    """Split a type into (vendor, domain, entity, action)."""
    if not isinstance(ce_type, str):
        raise ContractViolation(f"type must be str, got {type(ce_type).__name__}")
    if not TYPE_REGEX.match(ce_type):
        raise ContractViolation(
            f"type {ce_type!r} does not match type regex {TYPE_REGEX.pattern!r}"
        )
    parts = ce_type.split(".")
    return parts[0], parts[1], parts[2], parts[3]


def _banned_token_hint(token: str) -> str:
    """The §9 lesson, appended to an allowlist refusal when the offending token is banned.

    An allowlist check necessarily fires before assert_banned_tokens -- the
    allowlists are what make the *position* meaningful -- so a producer writing
    `bloodbank.evt.repo.claude.created` was told only "entity 'claude' not in
    allowlist (§7)". That is true and useless: it invites them to try another
    entity name, when the actual rule is that no entity name would ever have
    worked. Identity is never a token. Teach that here rather than reordering
    the pipeline, so EVERY caller of assert_type_shape gets the lesson -- not
    just the ones that go on to call assert_banned_tokens afterwards.
    """
    if token in BANNED_TOKENS:
        return (
            f"; and {token!r} is a BANNED TOKEN (§9) -- provider/CLI/model/repo "
            f"identity NEVER appears in a type or subject, under any position. "
            f"It belongs in actor.* (actor.cli, actor.provider, actor.model, "
            f"actor.agent_id) or data.*. No allowlisted name will fix this"
        )
    return ""


def assert_type_shape(ce_type: str) -> tuple[str, str, str]:
    """Assert §2. Returns (domain, entity, action) on success."""
    _, domain, entity, action = _split_type(ce_type)
    if domain not in ALLOWED_DOMAINS:
        raise ContractViolation(
            f"domain {domain!r} not in allowlist (§6)"
            f"{_banned_token_hint(domain)}; see docs/event-naming.md"
        )
    if entity not in ALLOWED_ENTITIES:
        raise ContractViolation(
            f"entity {entity!r} not in allowlist (§7)"
            f"{_banned_token_hint(entity)}; see docs/event-naming.md"
        )
    retired = RETIRED_PAIRS.get((domain, entity))
    if retired:
        raise ContractViolation(
            f"{domain}.{entity} is retired (§7): {retired}; see docs/event-naming.md"
        )
    domains = ENTITY_DOMAINS.get(entity)
    if domains is not None and domain not in domains:
        raise ContractViolation(f"entity {entity!r} is paired only with {sorted(domains)} (§7)")
    if domain == "game" and action not in GAME_ENTITY_ACTIONS.get(entity, ()):
        raise ContractViolation(f"unregistered game entity/action pair {entity}.{action} (§11.5)")
    if entity == "app_launch" and action != "recorded":
        raise ContractViolation("unregistered project.app_launch action (§11.5)")
    return domain, entity, action


def assert_banned_tokens(ce_type: str) -> None:
    """Assert §9: no provider/CLI/model names in type."""
    tokens = set(ce_type.split("."))
    intersect = tokens & BANNED_TOKENS
    if intersect:
        raise ContractViolation(
            f"type {ce_type!r} contains banned tokens {sorted(intersect)} (§9); "
            f"provider identity belongs in actor, not type"
        )


def assert_action_tense(action: str, kind: str) -> None:
    """Assert §5: past-tense for kind=event, imperative for kind=command, mirror for kind=reply."""
    if kind == "event":
        if action not in EVENT_ACTIONS:
            raise ContractViolation(
                f"event action {action!r} not in past-tense allowlist (§8.1); "
                f"events use past tense / past participle"
            )
        if action in {"response", "request"}:
            raise ContractViolation(
                f"action {action!r} is a noun, not a verb; use the verb pair "
                f"received/sent (§9)"
            )
    elif kind == "command":
        if action not in COMMAND_ACTIONS:
            raise ContractViolation(
                f"command action {action!r} not in imperative allowlist (§8.2); "
                f"commands use imperative present tense"
            )
    elif kind == "reply":
        # Replies mirror the command they answer.
        if action not in COMMAND_ACTIONS:
            raise ContractViolation(
                f"reply action {action!r} must mirror a command action (§5)"
            )
    else:
        raise ContractViolation(
            f"unknown kind {kind!r}; expected event|command|reply (§4)"
        )


def subject_for(ce_type: str, kind: str) -> str:
    """Build the NATS subject for (type, kind). §3.

    Type:    bloodbank.<domain>.<entity>.<action>
    Subject: bloodbank.<evt|cmd|rpy>.<domain>.<entity>.<action>
    """
    vendor, domain, entity, action = _split_type(ce_type)
    if kind not in KIND_MARKERS:
        raise ContractViolation(
            f"unknown kind {kind!r}; expected event|command|reply (§4)"
        )
    marker = KIND_MARKERS[kind]
    return f"{vendor}.{marker}.{domain}.{entity}.{action}"


def assert_subject_matches(subject: str, ce_type: str, kind: str) -> None:
    """Assert §3: subject mirrors type with the kind marker injected."""
    expected = subject_for(ce_type, kind)
    if subject != expected:
        raise ContractViolation(
            f"subject {subject!r} does not match expected {expected!r} "
            f"for type={ce_type!r} kind={kind!r}"
        )


