class BoundedRecallTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.calls = self.root / "calls.jsonl"
        fake = self.root / "hindsight"
        fake.write_text(FAKE_CLI)
        fake.chmod(0o700)
        patcher = mock.patch.dict(os.environ, {
            "HINDSIGHT_BIN": str(fake), "HS_JOURNAL_DIR": str(self.root / "journal"),
            "CALL_LOG": str(self.calls), "BB_HOOK_INVOCATION_ID": "t"})
        patcher.start()
        self.addCleanup(patcher.stop)
        self.addCleanup(mock.patch.stopall)
        self.bank = mock.patch.object(hindsight, "bank", return_value="fast").start()
        self.banks = mock.patch.object(hindsight, "recall_banks", return_value=["fast"]).start()

    def calls_made(self):
        return [json.loads(line) for line in self.calls.read_text().splitlines()] if self.calls.exists() else []

    def journal(self, session="s"):
        path = self.root / "journal/sessions" / f"claude-{session}.jsonl"
        return [json.loads(line) for line in path.read_text().splitlines()]

    def test_the_deadline_kills_a_stalled_bank_and_keeps_what_finished(self):
        self.banks.return_value = ["fast", "slow"]
        started = time.monotonic()
        with mock.patch.dict(os.environ, {"HINDSIGHT_RECALL_TIMEOUT": "1.0"}):
            output = hindsight.recall({"session_id": "s", "prompt": "how does the hub dispatch sync handlers?"},
                                      "claude", "UserPromptSubmit")
        elapsed = time.monotonic() - started
        self.assertLess(elapsed, 2.0, "the handler must return at its deadline, not when the slowest bank does")
        self.assertEqual(output["_hook_hub"]["reason"], "recall_partial")
        context = json.loads(output["stdout"])["hookSpecificOutput"]["additionalContext"]
        self.assertIn("fact from fast", context)
        slow_pid = next(call["pid"] for call in self.calls_made() if call["bank"] == "slow")
        time.sleep(0.1)
        with self.assertRaises(ProcessLookupError, msg="the stalled CLI must be killed, not orphaned"):
            os.kill(slow_pid, 0)
        per_bank = {row["bank"]: row for row in self.journal()[-1]["per_bank"]}
        self.assertEqual(per_bank["fast"]["status"], "ok")
        self.assertEqual(per_bank["slow"]["status"], "timeout")
        # Bounded by the deadline (measured from process start), never by the 30s sleep.
        self.assertLess(per_bank["slow"]["latency_ms"], 1500)

    def test_a_query_too_long_is_retried_once_at_half_length(self):
        self.banks.return_value = ["picky"]
        with mock.patch.dict(os.environ, {"PICKY_MAX": "300", "HINDSIGHT_RECALL_QUERY_MAX_CHARS": "500"}), \
             mock.patch.object(hindsight, "_ENCODER", None):
            output = hindsight.recall({"session_id": "s", "prompt": "please explain " + "the retry path " * 100},
                                      "claude", "UserPromptSubmit")
        queries = [len(call["query"]) for call in self.calls_made()]
        self.assertEqual(len(queries), 2)
        self.assertLessEqual(queries[1], queries[0] // 2 + 1)
        self.assertEqual(output["_hook_hub"]["status"], "succeeded")
        row = self.journal()[-1]["per_bank"][0]
        self.assertEqual((row["status"], row.get("retried")), ("ok", True))

    def test_a_dense_query_is_cut_to_the_servers_own_count(self):
        # Emoji, braille and block-drawing pastes run ~3 cl100k tokens a char:
        # half of the 1,000-char cap is still ~1,500 tokens, so halving alone
        # would be rejected twice and the prompt would get no memory at all.
        self.banks.return_value = ["dense"]
        with mock.patch.object(hindsight, "_ENCODER", None):
            output = hindsight.recall({"session_id": "s", "prompt": "why does the load graph look like this "
                                       + "⣿⣷⣶⣤⣀ " * 400}, "claude", "UserPromptSubmit")
        queries = [call["query"] for call in self.calls_made()]
        self.assertEqual(len(queries), 2)
        self.assertLessEqual(3 * len(queries[1]), 500)
        self.assertTrue(queries[1].startswith("why does the load graph"))
        self.assertEqual(output["_hook_hub"]["status"], "succeeded")
        row = self.journal()[-1]["per_bank"][0]
        self.assertEqual((row["status"], row.get("retried")), ("ok", True))

    def test_a_persistent_400_is_journaled_as_http_400(self):
        self.banks.return_value = ["picky"]
        with mock.patch.dict(os.environ, {"PICKY_MAX": "10"}):
            output = hindsight.recall({"session_id": "s", "prompt": "please explain the retry path in the publisher"},
                                      "claude", "UserPromptSubmit")
        row = self.journal()[-1]["per_bank"][0]
        self.assertEqual(row["status"], "http_400")
        self.assertIn("Query too long", row["detail"])
        self.assertEqual(output["_hook_hub"]["reason"], "recall_query_rejected")

    def test_every_bank_outcome_is_journaled(self):
        self.banks.return_value = ["fast", "void", "broken"]
        prompt = "<system-reminder>noise</system-reminder>\nhow does the hub journal recall outcomes per bank?"
        hindsight.recall({"session_id": "s", "prompt": prompt}, "claude", "UserPromptSubmit")
        event = self.journal()[-1]
        self.assertEqual(event["event"], "recall")
        self.assertEqual(event["query_len_raw"], len(prompt))
        self.assertEqual(event["query_len_clean"], len("how does the hub journal recall outcomes per bank?"))
        self.assertEqual(event["query_len_sent"], event["query_len_clean"])
        statuses = {row["bank"]: row["status"] for row in event["per_bank"]}
        self.assertEqual(statuses, {"fast": "ok", "void": "empty", "broken": "error"})
        for row in event["per_bank"]:
            self.assertIn("latency_ms", row)
            self.assertIn("results", row)
        self.assertEqual(event["failed_banks"], 1)
        self.assertTrue(event["returned_anything"])

    def test_the_query_sent_is_the_cleaned_one(self):
        hindsight.recall({"session_id": "s", "prompt": "/bmad-build-auto story 4-1 hosted auth refresh path"},
                         "claude", "UserPromptSubmit")
        self.assertEqual(self.calls_made()[0]["query"], "story 4-1 hosted auth refresh path")

    def test_a_harness_only_prompt_is_skipped_and_journaled(self):
        prompt = "<task-notification><task-id>x</task-id><status>completed</status></task-notification>"
        output = hindsight.recall({"session_id": "s", "prompt": prompt}, "claude", "UserPromptSubmit")
        self.assertEqual(output["_hook_hub"], {"status": "skipped", "reason": "query_under_min_length_after_cleanup",
                                               "exit_code": 0})
        self.assertEqual(self.calls_made(), [])
        event = self.journal()[-1]
        self.assertEqual((event["event"], event["reason"], event["query_len_clean"]),
                         ("recall_skipped", "query_under_min_length_after_cleanup", 0))


class _Models(http.server.BaseHTTPRequestHandler):
    models: dict[str, tuple[int, dict]] = {}
    delay = 0.0
    seen: list[str] = []

    def do_GET(self):  # noqa: N802
        type(self).seen.append(self.headers.get("Authorization", ""))
        time.sleep(type(self).delay)
        model = self.path.rsplit("/", 1)[-1]
        code, body = type(self).models.get(model, (404, {"detail": f"Mental model '{model}' not found"}))
        data = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def log_message(self, *args):
        pass


class BriefingTests(unittest.TestCase):
    def setUp(self):
        self.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _Models)
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        self.addCleanup(self.server.server_close)
        self.addCleanup(self.server.shutdown)
        _Models.delay = 0.0
        _Models.seen = []
        _Models.models = {
            "briefing": (200, {"id": "briefing", "name": "Project Briefing", "content": "Bloodbank is the event bus."}),
            "rules": (200, {"id": "rules", "name": "Conventions", "content": "Conventions: Generating content..."}),
        }
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        config = Path(self.temporary.name) / "config"
        config.write_text(f'api_url = "http://127.0.0.1:{self.server.server_port}"\napi_key = "from-config"\n')
        patcher = mock.patch.dict(os.environ, {"HINDSIGHT_CONFIG": str(config),
                                               "HS_JOURNAL_DIR": str(Path(self.temporary.name) / "journal")})
        patcher.start()
        self.addCleanup(patcher.stop)
        for name in ("HINDSIGHT_API_URL", "HINDSIGHT_API_KEY"):
            os.environ.pop(name, None)
        bank = mock.patch.object(hindsight, "bank", return_value="bloodbank")
        bank.start()
        self.addCleanup(bank.stop)

    def test_ready_models_are_injected_and_missing_or_pending_ones_skipped(self):
        output = hindsight.briefing({"session_id": "b", "source": "startup"}, "claude", "SessionStart")
        self.assertEqual(output["_hook_hub"]["reason"], "briefing_injected")
        context = json.loads(output["stdout"])["hookSpecificOutput"]
        self.assertEqual(context["hookEventName"], "SessionStart")
        text = context["additionalContext"]
        self.assertIn("# Hindsight briefing: bank `bloodbank`", text)
        self.assertIn("## Project Briefing", text)
        self.assertIn("Bloodbank is the event bus.", text)
        self.assertNotIn("Generating content", text)
        self.assertEqual(set(_Models.seen), {"Bearer from-config"}, "the key comes from ~/.hindsight/config")
        journal = Path(os.environ["HS_JOURNAL_DIR"]) / "sessions/claude-b.jsonl"
        event = json.loads(journal.read_text().splitlines()[-1])
        self.assertEqual(event["models"], {"briefing": "ok", "pitfalls": "not_found", "rules": "pending"})

    def test_nothing_ready_is_a_silent_skip(self):
        _Models.models = {}
        output = hindsight.briefing({"session_id": "b"}, "claude", "SessionStart")
        self.assertEqual((output["_hook_hub"]["status"], output["stdout"]), ("skipped", ""))

    def test_a_slow_api_never_blocks_the_session(self):
        _Models.delay = 2.0
        with mock.patch.dict(os.environ, {"HINDSIGHT_BRIEFING_TIMEOUT": "0.3"}):
            started = time.monotonic()
            output = hindsight.briefing({"session_id": "b"}, "claude", "SessionStart")
        self.assertLess(time.monotonic() - started, 1.0)
        self.assertEqual(output["_hook_hub"]["reason"], "no_briefing_models")

    def test_an_unreachable_api_is_a_silent_skip(self):
        Path(os.environ["HINDSIGHT_CONFIG"]).write_text('api_url = "http://127.0.0.1:9"\napi_key = "k"\n')
        output = hindsight.briefing({"session_id": "b"}, "claude", "SessionStart")
        self.assertEqual(output["_hook_hub"]["status"], "skipped")

    def test_a_resumed_session_is_not_briefed_twice(self):
        output = hindsight.briefing({"session_id": "b", "source": "resume"}, "claude", "SessionStart")
        self.assertEqual(output["_hook_hub"]["reason"], "session_resumed")
        self.assertEqual(_Models.seen, [])

    def test_the_briefing_is_capped(self):
        _Models.models = {name: (200, {"name": name.title(), "content": "x " * 20000})
                          for name in hindsight.BRIEFING_MODELS}
        with mock.patch.dict(os.environ, {"HINDSIGHT_BRIEFING_MAX_CHARS": "3000"}):
            output = hindsight.briefing({"session_id": "b"}, "claude", "SessionStart")
        self.assertLess(len(json.loads(output["stdout"])["hookSpecificOutput"]["additionalContext"]), 3600)


