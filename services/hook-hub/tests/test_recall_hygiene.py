class CleanupTests(unittest.TestCase):
    def test_a_task_notification_is_not_a_question(self):
        prompt = ("<task-notification>\n<task-id>bu11</task-id>\n<tool-use-id>toolu_1</tool-use-id>\n"
                  "<output-file>/tmp/x</output-file>\n<status>completed</status>\n"
                  "<summary>Background command \"run tests\" completed (exit code 0)</summary>\n"
                  "</task-notification>\nRead the output file to retrieve the result: /tmp/x")
        self.assertEqual(hindsight.clean_query(prompt), "")

    def test_system_reminders_are_dropped_and_the_user_kept(self):
        prompt = ("<system-reminder>\n# Environment update\n - Additional working directories added\n"
                  "</system-reminder>\nHow does the hook hub pick which banks to recall from?")
        self.assertEqual(hindsight.clean_query(prompt), "How does the hook hub pick which banks to recall from?")

    def test_a_raw_slash_command_keeps_its_arguments(self):
        self.assertEqual(hindsight.clean_query("/review-pr 123 please look at the retry logic"),
                         "123 please look at the retry logic")
        self.assertEqual(hindsight.clean_query("/plugin:skill-name   trailing args here"), "trailing args here")

    def test_a_rendered_slash_command_keeps_only_its_arguments(self):
        prompt = ("<command-message>bmad-build-auto</command-message>\n"
                  "<command-name>/bmad-build-auto</command-name>\n"
                  "<command-args>4-1-hosted-auth story, focus on the refresh token path</command-args>")
        self.assertEqual(hindsight.clean_query(prompt), "4-1-hosted-auth story, focus on the refresh token path")

    def test_a_leading_path_is_not_a_slash_command(self):
        prompt = "/home/me/code/foo/bar.py throws KeyError on startup"
        self.assertEqual(hindsight.clean_query(prompt), prompt)

    def test_local_command_output_and_caveats_are_dropped(self):
        prompt = ("<local-command-caveat>Caveat: The messages below were generated by the user while running "
                  "local commands.</local-command-caveat>\n"
                  "<local-command-stdout>Set effort level to xhigh</local-command-stdout>")
        self.assertEqual(hindsight.clean_query(prompt), "")

    def test_codex_and_teammate_frames_are_dropped(self):
        for prompt in (
            '<send_user_message_question_reply> [{"answer":"Phone","question":"Where?"}] </send_user_message_question_reply>',
            'Another Claude session sent a message: <teammate-message teammate_id="impl" color="blue"> '
            '{"type":"idle_notification"} </teammate-message>',
            "<environment_context>\n  <cwd>/x</cwd>\n</environment_context>",
            "<turn_aborted> The user interrupted the previous turn on purpose. </turn_aborted>",
            "This session is being continued from a previous conversation that ran out of context. Summary...",
        ):
            self.assertEqual(hindsight.clean_query(prompt), "", prompt)

    def test_an_unknown_kebab_wrapper_opening_a_line_is_a_harness_frame(self):
        prompt = "<foo-bar id=\"1\">\nharness payload\n</foo-bar>\nplease fix the flaky receipts test"
        self.assertEqual(hindsight.clean_query(prompt), "please fix the flaky receipts test")

    def test_inline_html_the_user_typed_survives(self):
        prompt = "why doesn't my <button>Click me</button> render inside the modal?"
        self.assertEqual(hindsight.clean_query(prompt), prompt)

    def test_pasted_content_is_the_users_own(self):
        prompt = "look at dumply's hooks.\n<pasted_content id=\"0f54\">the logs say ERROR 42</pasted_content>"
        self.assertEqual(hindsight.clean_query(prompt), "look at dumply's hooks. the logs say ERROR 42")

    def test_whitespace_is_collapsed(self):
        self.assertEqual(hindsight.clean_query("  why\n\n\tis   this slow?  "), "why is this slow?")


class TruncationTests(unittest.TestCase):
    def setUp(self):
        # The hub's interpreter has no tiktoken; pin the char path either way.
        patcher = mock.patch.object(hindsight, "_ENCODER", None)
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_a_short_query_is_untouched(self):
        self.assertEqual(hindsight.cap_query("why is recall slow"), "why is recall slow")

    def test_a_long_query_keeps_its_head_and_tail_under_the_cap(self):
        text = "Fix the failing deploy. " + "noise 0xdeadbeef /var/lib/x " * 400 + "What is the root cause?"
        capped = hindsight.cap_query(text)
        self.assertLessEqual(len(capped), 1000)
        self.assertTrue(capped.startswith("Fix the failing deploy."))
        self.assertTrue(capped.endswith("What is the root cause?"))
        self.assertIn(hindsight.ELISION, capped)

    def test_the_char_cap_is_configurable(self):
        with mock.patch.dict(os.environ, {"HINDSIGHT_RECALL_QUERY_MAX_CHARS": "200"}):
            self.assertLessEqual(len(hindsight.cap_query("word " * 500)), 200)

    def test_halving_halves(self):
        text = hindsight.cap_query("alpha beta gamma delta " * 200)
        self.assertLessEqual(len(hindsight.halve_query(text)), len(text) // 2 + 1)

    def test_the_token_path_is_used_when_an_encoder_exists(self):
        class Words:
            def encode(self, text, disallowed_special=()):
                return text.split()

            def decode(self, ids):
                return " ".join(ids)

        with mock.patch.object(hindsight, "_ENCODER", Words()):
            capped = hindsight.cap_query(" ".join(f"w{i}" for i in range(1000)))
        self.assertLessEqual(len(capped.split()), 401)
        self.assertTrue(capped.startswith("w0 ") and capped.endswith(" w999"))


